#Verificar Igualdade de Strings: Peça ao usuário duas palavras e use operadores de comparação para verificar se elas são iguais.

palavra1 = input("Digite uma palavra: ")
palavra2 = input("Digite outra palavra: ")

if palavra1 == palavra2:
    print("As palavras são iguais")
else:
    print("As palavras são diferentes")